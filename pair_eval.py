def load_config(config_path):
    """Loads and parses a YAML config file."""
    with open(config_path, 'r') as f:
        config = yaml.safe_load(f)
    return config 

def prepare_evaluation(output_dir):

    '''
    prepare the evaluation environment

    output_dir: st, the output directory of pair_scratch.py, contains logs dir and models dir (checkpoint dir) and training configs file
    '''
    config_path = os.path.join(output_dir, 'config.yaml')
    
    config = load_config(config_path)

    # === prepare dataset ===
    data_cfg = config['data']
    train_data_path = data_cfg['train_data_path']
    test_data_path = data_cfg['test_data_path']
    key_1, key_2 = data_cfg['key_1'], data_cfg['key_2']
    train_dataset, test_dataset = data_prepare(train_data_path, test_data_path, key_1, key_2)

    # === Model ===
    model_cfg = config['model']

    ## assert that the input feature number matches the feature number in the first sample.
    feature_num_1 = model_cfg['feature_num_1']
    feature_num_2 = model_cfg['feature_num_2']
    assert feature_num_1 == len(train_dataset[0]['omic_1'])
    assert feature_num_2 == len(train_dataset[0]['omic_2'])

    pair_model = pair_sr_scratch(
        feature_num_1=feature_num_1,
        feature_num_2=feature_num_2,
        hidden_params_1=model_cfg['hidden_params_1'],
        hidden_params_2=model_cfg['hidden_params_2'],
        embed_dim=model_cfg['embed_dim'],
        use_rmsnorm=model_cfg['use_rmsnorm'],
        use_residual=model_cfg['use_residual'],
        dropout_p=model_cfg['dropout_p'],)

    
    #=== Setup ===
    pair_model.set_dataset(train_dataset, test_dataset)
    pair_model.set_dataloader(batch_size=data_cfg['batch_size'])
    # === Loss ===
    loss_cfg = config['loss']
    pair_model.set_loss(
        vae_beta_1=loss_cfg['vae_beta_1'],
        vae_beta_2=loss_cfg['vae_beta_2'],
        clip_weight=float(loss_cfg['clip_weight']),
        cross_recon_1=float(loss_cfg['cross_recon_1']),
        cross_recon_2=float(loss_cfg['cross_recon_2']),
        temperature=float(loss_cfg['temperature']),
        trainable_clip_temperature=loss_cfg['trainable_clip_temperature']
    )
    print('✅ Evaluation environment ready')
    return pair_model

def single_model_evaluation(pair_model, ckpt_steps, output_dir, device = 'cpu'):
    ''''
    pair_model: pair_sr_scratch model
    ckpt_steps: checkpoint steps, a checkpoint is named as ckpt_steps.pth
    output_dir: the directory for one run, generated by pair_scratch.py
    device: cpu or 'cuda'
    '''
    eval_res_dir = os.path.join(output_dir, 'eval_result', f'{ckpt_steps}_result')
    os.makedirs(eval_res_dir, exist_ok=True)

    ckpt_path = os.path.join(output_dir, 'models', 'ckpt_%s.pth'%ckpt_steps)

    pair_model.load_model(ckpt_path)
    model = pair_model.model

    #===prediction===
    print('🚀 Start evaluation...')
    model = pair_model.model 
    model.to(device)
    model.eval()


    ## TO DO: evaluation using mini-batch
    x1 = pair_model.test_dataset.omic_1.to(device)
    x2 = pair_model.test_dataset.omic_2.to(device)
    print(f'test omic 1 shape {x1.shape}, omic 2 shape {x2.shape}')

    outputs, loss_dic = model(x1,x2)

    rna2atac = outputs['x2_c_recon'].detach().numpy()
    atac2rna = outputs['x1_c_recon'].detach().numpy()
    print(f'generated rna2atac shape {rna2atac.shape}, atac2rna shape {atac2rna.shape}')


    #=== save predict result =====
    X = np.concatenate([x1, atac2rna], axis = 0)
    adata = ad.AnnData(X)
    adata.obs['label'] = ['ori_rna']*x1.shape[0] + ['pred_rna']*x1.shape[0]

    adata.write_h5ad(os.path.join(eval_res_dir, 'rna_test.h5ad'))

    X = np.concatenate([x2, rna2atac], axis = 0)
    adata = ad.AnnData(X)
    adata.obs['label'] = ['ori_atac']*x1.shape[0] + ['pred_atac']*x1.shape[0]

    adata.write_h5ad(os.path.join(eval_res_dir, 'atac_test.h5ad'))

    print('Cross prediction pipe over')

    # #===rna prediction evaluation===     ## Tims costly if all perform feature correlation evaluation
    # eval_pipe(eval_res_dir, type = 'rna')  
    # #===atac prediction evaluation===
    # eval_pipe(eval_res_dir, type = 'atac')

    #################################################################################################################
    # === embedding eavluation pipe ===
    z_mu = outputs['x1']['z_mu']   #model.model_1.get_embedding(x1)
    y_mu = outputs['x2']['z_mu']

    N = z_mu.shape[0]
    z_mu = z_mu.detach().cpu().numpy()
    y_mu = y_mu.detach().cpu().numpy()

    ## perform evaluation
    res = {}
    ### calculate top_k hit rate
    for i in [1,5,10,15,20,30,50,100]:
        res[f'top_{i}_hit'] = calculate_hit_rate(z_mu, y_mu, i, metric = 'cosine')

    ### calculate metric score
    acc, ms, fs = matching_metrics(x=z_mu, y = y_mu, metric='cosine')
    res['acc'] = acc 
    res['mathscore'] = ms 
    res['foscttm'] = fs
    with open(os.path.join(eval_res_dir, 'match_metric.json'), 'w') as f:
        json.dump(res, f)

    ### perform UMAP plot
    mu = np.concatenate([z_mu, y_mu], axis = 0)
    adata = ad.AnnData(X = np.random.rand(2*N,10))
    adata.obs.loc[:,'batch'] = ['rna']*N + ['atac']*N
    adata.obsm['mu'] = mu 

    sc.pp.neighbors(adata, use_rep='mu')
    sc.tl.umap(adata, min_dist = 0.5)
    sc.pl.umap(adata, color='batch', show = False)
    plt.savefig(os.path.join(eval_res_dir, f'embedding_umap.png'), bbox_inches='tight')
    print(f'{ckpt_steps}_Evaluation OVER')
    return None
def single_model_whole_evaluation(output_dir):
    pair_model = prepare_evaluation(output_dir)
    
    
    for ckpt_steps in tqdm(range(1,21)):
        ckpt_steps = int(500*ckpt_steps)
        single_model_evaluation(pair_model, ckpt_steps, output_dir) 
    print('✅ Evaluation OVER')
    return None

