def eval_pipe(eval_dir):

    '''
    load data
    '''
    data_path = os.path.join(eval_dir, 'sc_test.h5ad')
    scdata = sc.read_h5ad(data_path) 

    '''
    perform match eval in rna embedding space 
    '''

    rna_embed = scdata.obsm['R2R']  ## embedding generated by rna to recover rna
    atac_embed = scdata.obsm['A2R']  ## embedding generated by atac to recover rna
                                     ## this two embedding are in the same space
    ## IF want to eval the embedding match performance in atac embedding space
    ## use A2A , R2A 
    ## we use R2R A2R because generally rna embedding has better performance than atac embedding 

    ## perform evaluation
    res = {}
    ### calculate top_k hit rate
    for i in [1,5,10,15,20,30,50,100]:
        res[f'top_{i}_hit'] = calculate_hit_rate(rna_embed,atac_embed, i, metric = 'euclidean')

    ### calculate metric score
    acc, ms, fs = matching_metrics(x=rna_embed, y = atac_embed, metric='euclidean')
    res['acc'] = acc 
    res['mathscore'] = ms 
    res['foscttm'] = fs
    with open(os.path.join(eval_dir, 'match_metric.json'), 'w') as f:
        json.dump(res, f)

    ### UMAP visualization  ###
    N = scdata.shape[0]
    adata = ad.AnnData(X = np.random.rand(2*N,10))
    adata.obs.loc[:,'batch'] = ['rna']*N + ['atac']*N
    mu = np.concatenate([rna_embed, atac_embed], axis = 0)
    adata.obsm['mu'] = mu   
    sc.pp.neighbors(adata, use_rep='mu')    
    sc.tl.umap(adata, min_dist = 0.5)
    sc.pl.umap(adata, color='batch',show = False)
    plt.savefig(os.path.join(eval_dir, 'embedding_umap.png'), bbox_inches='tight')

    print('SCB evaluation OVER')

